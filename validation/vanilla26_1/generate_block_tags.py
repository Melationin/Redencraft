"""Generate deterministic built-in 26.1 block tags from Mojang export."""
import argparse
import hashlib
import json
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('--root', type=Path, required=True)
parser.add_argument('--output', type=Path, required=True)
args = parser.parse_args()
asset = args.root / 'assets/block26_1/block_tags.tsv'
manifest = json.loads((asset.parent / 'tags_manifest.json').read_text(encoding='utf-8'))
if manifest['jar_sha1'] != '3872a7f07a1a595e651aef8b058dfc2bb3772f46':
    raise SystemExit('unexpected vanilla server hash')
if manifest['classes_sha256'] != 'a7fed6f7d88379349e35ae0c6e9881d4484605132f6f620376a3868eea6cce52':
    raise SystemExit('unexpected extracted server classes hash')
if hashlib.sha256(asset.read_bytes()).hexdigest() != manifest['tags_sha256']:
    raise SystemExit('tag asset hash does not match manifest')
blocks = {line.split('\t')[1] for line in
          (args.root / 'assets/protocol775/blocks.tsv').read_text().splitlines()}
tags, members = [], []
for line in asset.read_text(encoding='utf-8').splitlines():
    name, values = line.split('\t')
    entries = values.split(',') if values else []
    if entries != sorted(set(entries)) or any(entry not in blocks for entry in entries):
        raise SystemExit(f'invalid tag members: {name}')
    tags.append((name, len(members), len(entries)))
    members.extend(entries)
if len(tags) != manifest['rows'] or [x[0] for x in tags] != sorted(set(x[0] for x in tags)):
    raise SystemExit('invalid tag count, order, or duplicate')
out = ['// Generated by validation/vanilla26_1/generate_block_tags.py; do not edit.',
       'static constexpr std::string_view kBlockTagMembers[] = {']
out.extend('    "' + entry + '",' for entry in members)
out.append('};')
out.append('static constexpr TagEntry kBlockTags[] = {')
out.extend(f'    {{"{name}", {start}, {count}}},' for name, start, count in tags)
out.append('};')
args.output.write_text('\n'.join(out) + '\n', encoding='utf-8')
print(f'generated {len(tags)} block tags, {len(members)} memberships')
