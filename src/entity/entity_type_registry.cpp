const EntityType *entityType(const std::string &name) {
  const auto n = canonical(name);
  static const auto byName = [] {
    phmap::flat_hash_map<std::string, const EntityType *, AnkerlStringHash,
                         std::equal_to<>>
        m;
    for (const auto &entry : entityRegistry())
      m.emplace(entry.name, &entry);
    return m;
  }();
  const auto it = byName.find(n);
  return it == byName.end() ? nullptr : it->second;
}

const EntityType *entityTypeByProtocolId(int protocolId) {
  const auto &entries = entityRegistry();
  if (protocolId < 0 || static_cast<std::size_t>(protocolId) >= entries.size())
    return nullptr;
  return &entries[static_cast<std::size_t>(protocolId)];
}
